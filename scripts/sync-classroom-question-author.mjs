#!/usr/bin/env node

/* eslint-disable @typescript-eslint/explicit-function-return-type -- standalone Node sync script */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(repoRoot, 'skills/simulator-question-author')
const target = resolve(repoRoot, 'skills/classroom-question-author')
const checkOnly = process.argv.includes('--check')

const mappings = [
  ['references/grading-budget.md', 'references/shared/grading-budget.md'],
  ['references/json-artifact-schemas.md', 'references/shared/json-artifact-schemas.md'],
  ['references/grading-dsl-and-evaluation.md', 'references/shared/grading-dsl-and-evaluation.md'],
  ['references/capability-snapshot.json', 'references/capability-snapshot.json'],
  ['assets/question-studio-project.template.json', 'assets/question-studio-project.template.json'],
  ['assets/question-package.template.json', 'assets/question-package.template.json'],
  ['assets/solution-topology.template.json', 'assets/solution-topology.template.json'],
  ['assets/coverage.template.json', 'assets/coverage.template.json'],
  ['scripts/grading-budget.mjs', 'scripts/grading-budget.mjs'],
  ['scripts/validate-artifacts.mjs', 'scripts/validate-core.mjs'],
  [
    'examples/quickcart/quickcart-flash-sale.simulator-question-project.json',
    'examples/quickcart-classroom/quickcart-flash-sale.simulator-question-project.json'
  ],
  [
    'examples/quickcart/quickcart-flash-sale.question-package.json',
    'examples/quickcart-classroom/quickcart-flash-sale.question-package.json'
  ],
  [
    'examples/quickcart/quickcart-flash-sale.solution-topology.json',
    'examples/quickcart-classroom/quickcart-flash-sale.solution-topology.json'
  ],
  [
    'examples/quickcart/quickcart-flash-sale.coverage.json',
    'examples/quickcart-classroom/quickcart-flash-sale.coverage.json'
  ]
]

function expectedCardReference() {
  const snapshot = JSON.parse(readFileSync(resolve(source, 'references/capability-snapshot.json')))
  const rows = snapshot.classroom.cards
    .map((card) => {
      const copies = card.copies ? `${card.copies.min}–${card.copies.max}` : 'fixed at 1'
      return `| \`${card.id}\` | ${card.label} | ${card.role} | ${card.covers.map((type) => `\`${type}\``).join(', ')} | ${copies} |`
    })
    .join('\n')
  return `# Generated Classroom Concept Cards

Generated by \`scripts/sync-classroom-question-author.mjs\` from the simulator
capability snapshot. Do not edit this file by hand.

| Card | Learner label | Behavior | Engine types | Copies |
| --- | --- | --- | --- | --- |
${rows}

Capacity-bound cards require an explicit \`capacityRps\` given. Passthrough cards
support topology lessons only unless a dedicated Classroom behavior says otherwise.
`
}

const generated = [['references/concept-cards.md', expectedCardReference()]]
let drift = false

function compareOrWrite(relative, expected) {
  const path = resolve(target, relative)
  if (checkOnly) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
      console.error(`Classroom skill shared file is stale: ${relative}`)
      drift = true
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, expected)
}

for (const [from, to] of mappings) {
  compareOrWrite(to, readFileSync(resolve(source, from), 'utf8'))
}
for (const [to, expected] of generated) compareOrWrite(to, expected)

if (drift) process.exit(1)
console.log(
  checkOnly
    ? 'Classroom Question Author shared files are current.'
    : 'Synchronized Classroom Question Author shared files.'
)
